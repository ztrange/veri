def defined_case_names():
    """The function names defined in the files that mention any named case at all: a function's name is in its file's
    text, so a file that mentions none of the 59 defines none of them, and is not parsed."""
    wanted = DELETE + KEEP + REDUCE
    names = set()
    for path in HERE.rglob("*.py"):
        if path.resolve() == Path(__file__).resolve():
            continue
        text = path.read_text(encoding="utf-8")
        if not any(name in text for name in wanted):
            continue
        tree = ast.parse(text)
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                names.add(node.name)
    return names


@pytest.mark.tree_audit("every test module under tests/py/")
def test_the_27_delete_cases_are_gone_and_the_23_keep_and_13_reduce_cases_remain_2782():
    assert (len(DELETE), len(KEEP), len(REDUCE)) == (27, 23, 9)
    defined = defined_case_names()
    still_defined = sorted(n for n in DELETE if n in defined)
    missing = sorted(n for n in KEEP + REDUCE if n not in defined)
    assert (still_defined, missing) == ([], [])
