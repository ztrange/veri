#!/usr/bin/env python3
"""check-walkthrough.py — verify docs/walkthrough.html is current and self-consistent.

The page is generated by build-walkthrough.py from the real scripts, so the check that
matters is simply: does regenerating produce what is committed? That fails both when a
script has changed without its commentary, and when someone hand-edits the output.

On top of that it verifies the properties the page claims:

  * every script's COMPLETE source appears, byte-for-byte, at the right line numbers
  * every in-page link resolves to an id that exists
  * every tooltip reference has a matching reference entry, and vice versa
  * tags balance
  * the capability index still lists exactly the repo's tags, newest first in git's
    version order — and has not silently vanished in a tree that does have tags
  * the TDD-loop figure still agrees with the two files it describes — the phases
    build-verify-prompt.sh accepts, and SKILL.md's revise budget. That figure is the
    one part of the page not generated from the scripts, so it is the one part that
    can go stale without `make docs` noticing.

Run via `make docs-check`. Deliberately NOT part of `make test`: veri refuses to start a
cycle on a red baseline, and prose drifting behind code should not block a TDD run.

Exit: 0 all checks pass, 1 drift found (details on stdout).
"""
import sys
# Never cache these modules. commentary.py is edited constantly, and a same-size
# edit inside one mtime second is enough for Python to reuse stale bytecode and
# generate a page from prose that no longer exists.
sys.dont_write_bytecode = True
import html
import json
import pathlib
import re
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SCRIPTS_DIR = ROOT / "skills" / "tdd" / "scripts"
PAGE = HERE / "walkthrough.html"

bad = []
doc = PAGE.read_text()

# 1 ── the committed page is what the generator produces ────────────────────────
proc = subprocess.run([sys.executable, str(HERE / "build-walkthrough.py"), "--stdout"],
                      capture_output=True, text=True, cwd=str(ROOT))
if proc.returncode != 0:
    bad.append("generator failed:\n" + proc.stderr.strip())
elif proc.stdout != doc:
    bad.append("projects/docs/walkthrough.html is stale — run `make docs` "
               "(generated output differs from the committed file)")
    print("regenerated: %d bytes / committed: %d bytes" % (len(proc.stdout), len(doc)))
else:
    print("generated output matches the committed page")

# 2 ── every script's full source is present, verbatim ──────────────────────────
sys.path.insert(0, str(HERE / "wt"))
import commentary as com          # noqa: E402
import primer as primer_mod       # noqa: E402

blocks = re.findall(r'<pre class="src" style="counter-reset: ln (\d+)">(.*?)</pre>', doc, re.S)
by_start = {}
# A line inside a version-tagged hunk wraps in `<span class="l hunk" data-tag=… title=…>`
# on the run's first line and `<span class="l hunk cont">` on the rest of it, instead of
# the plain `<span class="l">`. The class and the attributes are decoration ON the line,
# not content IN it — the same bytes are still inside — so all three forms are read as
# source here. Skipping a marked form would drop a real line from the comparison and
# report the whole chunk as drift the moment a hunk gets tagged.
for ctr, body in blocks:
    lines = [html.unescape(re.sub(r"</?span[^>]*>", "", m.group(1)))
             for m in re.finditer(r'<span class="l(?: hunk(?: cont)?)?"[^>]*>(.*?)</span>(?=\n|$)',
                                  body)]
    by_start.setdefault(int(ctr) + 1, []).append(lines)

covered = 0
for spec in com.SCRIPTS:
    path = SCRIPTS_DIR / spec["file"]
    if not path.exists():
        bad.append("missing script %s" % spec["file"]); continue
    src = path.read_text().splitlines()
    for ch in spec["chunks"]:
        a, b = ch["lines"]
        want = src[a - 1:b]
        cands = by_start.get(a, [])
        if want not in cands:
            bad.append("%s L%d-%d: source in page does not match the file" % (spec["file"], a, b))
        else:
            covered += len(want)
print("verbatim source: %d lines checked across %d scripts" % (covered, len(com.SCRIPTS)))

# 3 ── links, references, tags ──────────────────────────────────────────────────
# strip <script> bodies first: JS string literals contain href="#..." fragments
# that are code, not page links.
prose = re.sub(r"<script>.*?</script>", "", doc, flags=re.S)
ids = set(re.findall(r'id="([^"]+)"', prose))
targets = set(re.findall(r'href="#([^"]+)"', prose))
if targets - ids:
    bad.append("dangling links: %s" % sorted(targets - ids))

primer_ids = {i["id"] for g in primer_mod.PRIMER for i in g["items"]}
used = set(re.findall(r'data-ref="([^"]+)"', doc))
if used - primer_ids:
    bad.append("tooltip refs with no reference entry: %s" % sorted(used - primer_ids))
if used - ids:
    bad.append("tooltip refs whose anchor is missing: %s" % sorted(used - ids))

m = re.search(r"window\.__VERI_TIPS__ = (\{.*?\});", doc, re.S)
if not m:
    bad.append("tooltip data block missing")
else:
    tips = json.loads(m.group(1))
    if set(tips) != primer_ids:
        bad.append("tooltip data out of sync with the reference section")
    if used - set(tips):
        bad.append("refs with no tooltip data: %s" % sorted(used - set(tips)))
    print("references: %d entries, %d distinct refs used, all resolve" % (len(tips), len(used)))

# 4 ── the location indicators: one model, three renderings ────────────────────
# The rail, the scrollspy and the breadcrumb all derive from nav_entries(). These
# checks are what "they cannot disagree" actually means, plus the two regressions
# that were found by putting the page in a browser.

if not doc.startswith("<!doctype html>"):
    bad.append("no <!doctype html> — the page renders in quirks mode, where "
               "document.scrollingElement is <body> and sticky/scroll measurement break")

m = re.search(r"window\.__VERI_NAV__ = (\[.*?\]);", doc, re.S)
if not m:
    bad.append("scrollspy model (window.__VERI_NAV__) missing from the page")
else:
    nav = json.loads(m.group(1))
    nav_ids = [e["id"] for e in nav]
    if not nav_ids:
        bad.append("scrollspy model is empty")
    # every entry must resolve to a heading AND to a rail link, or the spy silently
    # skips it: getElementById returns null and the row is dropped.
    missing_heading = [i for i in nav_ids if ('id="%s"' % i) not in prose]
    rail_html = re.search(r'<aside class="rail">(.*?)</aside>', doc, re.S)
    rail_hrefs = re.findall(r'<a href="#([^"]+)"', rail_html.group(1)) if rail_html else []
    missing_link = [i for i in nav_ids if i not in rail_hrefs]
    orphan_link = [h for h in rail_hrefs if h not in nav_ids]
    if missing_heading:
        bad.append("nav entries with no heading on the page: %s" % missing_heading)
    if missing_link:
        bad.append("nav entries with no rail link: %s" % missing_link)
    if orphan_link:
        bad.append("rail links not in the scrollspy model: %s" % orphan_link)
    if [e for e in nav if not e.get("trail")]:
        bad.append("nav entries with an empty breadcrumb trail")
    print("indicators: %d nav entries, %d rail links, all resolve" % (len(nav_ids), len(rail_hrefs)))

# the breadcrumb's home crumb points at #top; without it the link is dead
if 'href="#top"' in prose and 'id="top"' not in prose:
    bad.append('breadcrumb home links to #top but no element has id="top"')

# REGRESSION: .ann-head must not be sticky. Its parent .ann is overflow:hidden, which
# makes .ann the sticky container — so the header can never stick to the viewport, only
# sit at a fixed offset inside its own box. At top:var(--crumb-h) it sat 44px down and
# covered line 1 of all 11 listings (#!/usr/bin/env bash, invisible).
ann_head = re.search(r"\.ann-head\{([^}]*)\}", doc)
if ann_head and "position:sticky" in ann_head.group(1).replace(" ", ""):
    bad.append(".ann-head is position:sticky again — its overflow:hidden parent scopes "
               "the stickiness, and a non-zero top hides line 1 of every listing")

# REGRESSION: the scrollspy must not depend on requestAnimationFrame alone. A document
# that is not being painted gets no frames, the in-flight latch never clears, and the
# indicator stops for the life of the page — including after it becomes visible again.
spy = doc[doc.rfind("__VERI_NAV__"):]
if "requestAnimationFrame" in spy and "setTimeout" not in spy:
    bad.append("scrollspy schedules on requestAnimationFrame with no timer fallback")

# 5 ── the TDD-loop figure vs the two files it describes ────────────────────────
# Everything else on this page is generated FROM the scripts, so it cannot drift.
# This one figure is the exception: it names the three phases, their order, and the
# revise budget — and no script emits any of that, by design (no file under
# scripts/ knows a phase exists; phase is a string the conductor passes down). So
# the figure is the only part of the page that can go stale without `make docs`
# noticing. These two checks close that hole against the authorities:
#   * the accepted phases, from build-verify-prompt.sh's own case arm — executable,
#     not prose, and the thing that would actually reject a renamed phase
#   * the revise budget, from SKILL.md, which owns it
# Both fail closed: if the pattern can no longer be located the guard says so
# rather than passing silently.
SKILL = SCRIPTS_DIR.parent / "SKILL.md"   # relative, so only SCRIPTS_DIR moves
# scoped to the section, or the search runs on into the NEXT figure and reports a
# missing figure as a phase mismatch instead
sect = re.search(r'<h3 id="tddloop">(.*?)(?=<h3 |\Z)', prose, re.S)
fig = re.search(r'<figure class="dataflow">.*?</figure>', sect.group(1), re.S) if sect else None
if not fig:
    bad.append("the TDD-loop figure is gone from the page (no #tddloop section, or no "
               "figure inside it)")
else:
    fig = fig.group(0)
    arm = re.search(r'^case "\$phase" in\n\s*([a-z|]+)\)',
                    (SCRIPTS_DIR / "build-verify-prompt.sh").read_text(), re.M)
    if not arm:
        bad.append("cannot find the phase case arm in build-verify-prompt.sh — the "
                   "TDD-loop figure's phase names can no longer be checked")
    else:
        phases = arm.group(1).split("|")
        drawn = re.findall(r">([A-Z][a-z]+) &mdash; ", fig)
        # The figure draws the loop's phases, not every phase the builder accepts: plan
        # (#439), rebase (#238) and transform (#499) verify other things than a cycle
        # step. So each drawn phase must be one the builder accepts, in its order; a
        # renamed or reordered loop phase still fails, which is what this guards.
        lowered = [d.lower() for d in drawn]
        if not drawn or [p for p in phases if p in lowered] != lowered:
            bad.append("the TDD-loop figure draws phases %s; build-verify-prompt.sh "
                       "accepts %s" % (drawn, phases))
        else:
            print("TDD loop: %d phases, each accepted by build-verify-prompt.sh, in its order"
                  % len(drawn))

    budget = re.search(r"`REVISE_BUDGET`[^.]*?\*\*default (\d+)\*\*", SKILL.read_text())
    claimed = set(re.findall(r"&le; (\d+) attempts", prose))
    if not budget:
        bad.append("cannot find REVISE_BUDGET's default in SKILL.md — the page's "
                   "'&le; N attempts' claims can no longer be checked")
    elif not claimed:
        bad.append("no '&le; N attempts' claim left on the page to check against "
                   "SKILL.md's REVISE_BUDGET")
    elif claimed != {budget.group(1)}:
        bad.append("the page claims a revise budget of %s; SKILL.md's REVISE_BUDGET "
                   "defaults to %s" % (sorted(claimed), budget.group(1)))
    else:
        print("revise budget: the page and SKILL.md both say %s" % budget.group(1))

# 6 ── the capability index vs the tags it claims to list ───────────────────────
# The index is generated from annotated tags, so the failure worth guarding is not
# "someone edited it" — it is the version layer silently vanishing (a git that could
# not be read leaves a page with no index and no error) or coming out mis-ordered.
real = subprocess.run(["git", "-C", str(ROOT), "tag", "--sort=v:refname"],
                      capture_output=True, text=True)
real = [t for t in real.stdout.split() if re.fullmatch(r"v\d+\.\d+", t)] if real.returncode == 0 else []
shown = re.findall(r'<span class="vtag">(v[\d.]+)</span>', prose)
badges = set(re.findall(r'<span class="vbadge">since <b>(v[\d.]+)</b>', prose))
badges |= set(re.findall(r'&middot; changed <b>(v[\d.]+)</b>', prose))

if not real:
    print("versions: this tree has no tags — version layer correctly absent"
          if not shown else "")
    if shown:
        bad.append("the page lists versions %s but this tree has no tags" % shown)
elif not shown:
    bad.append("this tree has %d version tags but the page lists none — the build "
               "could not read git, and said nothing" % len(real))
else:
    if set(shown) - set(real):
        bad.append("the index lists versions that are not tags: %s"
                   % sorted(set(shown) - set(real)))
    if badges - set(real):
        bad.append("script badges name versions that are not tags: %s"
                   % sorted(badges - set(real)))
    # newest first, in GIT's version order. Plain lexical sort puts v0.9 above v0.10,
    # which would bury the newest release in the middle of the list — the exact bug
    # `git tag --sort=-v:refname` exists to prevent, asserted here on the output.
    # Every tag must be LISTED, not merely in the right order among those that are.
    # The staleness check above usually reaches this case too, since a new tag changes
    # what a rebuild produces — but it answers "run `make docs`" for every cause alike.
    # This one names the actual cause, which is the difference between a one-line fix
    # and a hunt; cutting a tag rebuilds nothing, so it is a cause worth naming. It also
    # stands on its own wherever the page was built with a different view of the tags
    # than the checker has.
    absent = [t for t in real if t not in set(shown)]
    if absent:
        bad.append("tags missing from the capability index: %s — cut after the page "
                   "was last built; run `make docs`" % absent)
    want = list(reversed(real))
    if not absent and shown != want:
        bad.append("the index is out of order: %s, expected %s (git version sort — "
                   "lexically v0.9 sorts after v0.10)" % (shown, want))
    elif not absent:
        print("versions: %d tags, index newest-first, %d script badges all resolve"
              % (len(shown), len(badges)))

for tag in ("div", "span", "pre", "p", "table", "svg"):
    o = len(re.findall(r"<%s[ >]" % tag, doc)); c = len(re.findall(r"</%s>" % tag, doc))
    if o != c:
        bad.append("tag balance <%s>: %d open / %d close" % (tag, o, c))

print("\n".join("FAIL: " + b for b in bad) if bad else "\nALL CHECKS PASS")
sys.exit(1 if bad else 0)
